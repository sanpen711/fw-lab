  user_id=(select auth.uid())
  or exists(select 1 from public.game_parties p where p.id=party_id and p.captain_id=(select auth.uid()))
  or (
    exists(select 1 from public.game_parties p where p.id=party_id and p.captain_id=game_party_contacts.user_id)
    and exists(select 1 from public.game_party_members m where m.party_id=game_party_contacts.party_id and m.user_id=(select auth.uid()) and m.state='accepted')
  )
);

