-- 6. 公开处刑记录写入
create or replace function public.fw_public_name(p_user_id uuid)
returns text language sql security definer set search_path = public as $$
  select coalesce((select nickname from public.profiles where id = p_user_id), '某位研究员');
$$;

create or replace function public.fw_log_moderation(
  p_target_type text,
  p_target_id text,
  p_target_user_id uuid,
  p_action text,
  p_reason text default '违反研究所公约',
  p_duration_text text default null,
  p_public_visible boolean default true,
  p_expires_at timestamptz default null
)
returns bigint language plpgsql security definer set search_path = public as $$
declare new_id bigint;
begin
  if not public.is_admin() then raise exception 'Only admin can write moderation logs'; end if;
  insert into public.moderation_logs(target_type,target_id,target_user_id,target_display_name,action,reason,duration_text,public_visible,created_by,expires_at)
  values (p_target_type,p_target_id,p_target_user_id,public.fw_public_name(p_target_user_id),p_action,coalesce(nullif(trim(p_reason),''),'违反研究所公约'),p_duration_text,coalesce(p_public_visible,true),auth.uid(),p_expires_at)
  returning id into new_id;
  return new_id;
end;
$$;

-- 7. 管理操作 RPC
create or replace function public.admin_moderate_user(p_target_user_id uuid,p_action text,p_mute_minutes int default null,p_reason text default '违反研究所公约',p_public_visible boolean default true)
returns void language plpgsql security definer set search_path = public as $$
declare target_role text; until_time timestamptz; duration_label text;
begin
  if not public.is_admin() then raise exception 'Only admin can moderate users'; end if;
  select role into target_role from public.profiles where id = p_target_user_id;
  if target_role is null then raise exception '用户不存在'; end if;
  if target_role = 'admin' then raise exception '不能处理管理员账号'; end if;
  if p_action = 'ban' then
    update public.profiles set is_banned = true, updated_at = now() where id = p_target_user_id;
    perform public.fw_log_moderation('user',p_target_user_id::text,p_target_user_id,'ban',p_reason,null,p_public_visible,null);
  elsif p_action = 'unban' then
    update public.profiles set is_banned = false, updated_at = now() where id = p_target_user_id;
    perform public.fw_log_moderation('user',p_target_user_id::text,p_target_user_id,'unban',p_reason,null,p_public_visible,null);
  elsif p_action = 'mute' then
    until_time := now() + make_interval(mins => greatest(coalesce(p_mute_minutes,1440),1));
    duration_label := case when coalesce(p_mute_minutes,1440) >= 1440 then (coalesce(p_mute_minutes,1440)/1440)::text || ' 天' when coalesce(p_mute_minutes,1440) >= 60 then (coalesce(p_mute_minutes,1440)/60)::text || ' 小时' else coalesce(p_mute_minutes,1440)::text || ' 分钟' end;
    update public.profiles set muted_until = until_time, updated_at = now() where id = p_target_user_id;
    perform public.fw_log_moderation('user',p_target_user_id::text,p_target_user_id,'mute',p_reason,duration_label,p_public_visible,until_time);
  elsif p_action = 'unmute' then
    update public.profiles set muted_until = null, updated_at = now() where id = p_target_user_id;
    perform public.fw_log_moderation('user',p_target_user_id::text,p_target_user_id,'unmute',p_reason,null,p_public_visible,null);
  else raise exception '未知处理动作'; end if;
end;
$$;

create or replace function public.admin_moderate_post(p_post_id bigint,p_delete boolean default true,p_reason text default '内容不适合公开展示',p_public_visible boolean default true)
returns void language plpgsql security definer set search_path = public as $$
declare owner_id uuid;
begin
  if not public.is_admin() then raise exception 'Only admin can moderate posts'; end if;
  select user_id into owner_id from public.posts where id = p_post_id;
  if owner_id is null then raise exception '帖子不存在'; end if;
  update public.posts set is_deleted = p_delete where id = p_post_id;
  perform public.fw_log_moderation('post',p_post_id::text,owner_id,case when p_delete then 'delete_post' else 'restore_post' end,p_reason,null,p_public_visible,null);
end;
$$;

