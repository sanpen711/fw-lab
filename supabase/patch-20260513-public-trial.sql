-- 1. 公开处刑记录
create table if not exists public.moderation_logs (
  id bigint generated by default as identity primary key,
  target_type text not null default 'user',
  target_id text,
  target_user_id uuid references public.profiles(id) on delete set null,
  target_display_name text not null default '某位研究员',
  action text not null default 'system_note',
  reason text not null default '违反研究所公约',
  duration_text text,
  public_visible boolean not null default true,
  is_revoked boolean not null default false,
  created_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now(),
  expires_at timestamptz
);

create index if not exists moderation_logs_public_idx on public.moderation_logs(public_visible, is_revoked, created_at desc);
create index if not exists moderation_logs_user_idx on public.moderation_logs(target_user_id, created_at desc);
alter table public.moderation_logs enable row level security;

drop policy if exists "moderation_logs_public_read" on public.moderation_logs;
create policy "moderation_logs_public_read" on public.moderation_logs for select using (public_visible = true and is_revoked = false);

drop policy if exists "moderation_logs_admin_read" on public.moderation_logs;
create policy "moderation_logs_admin_read" on public.moderation_logs for select using (public.is_admin());

drop policy if exists "moderation_logs_admin_insert" on public.moderation_logs;
create policy "moderation_logs_admin_insert" on public.moderation_logs for insert with check (public.is_admin());

drop policy if exists "moderation_logs_admin_update" on public.moderation_logs;
create policy "moderation_logs_admin_update" on public.moderation_logs for update using (public.is_admin()) with check (public.is_admin());

grant select on public.moderation_logs to anon, authenticated;
grant insert, update on public.moderation_logs to authenticated;
grant usage, select on all sequences in schema public to authenticated;

-- 2. 管理员可读取软删除内容，普通用户仍只看未删除内容
drop policy if exists "posts_select_public" on public.posts;
create policy "posts_select_public" on public.posts for select using (is_deleted = false or public.is_admin());

drop policy if exists "comments_select_public" on public.comments;
create policy "comments_select_public" on public.comments for select using (is_deleted = false or public.is_admin());

do $$ begin
  if to_regclass('public.chat_messages') is not null then
    execute 'drop policy if exists "chat_messages_select_public" on public.chat_messages';
    execute 'create policy "chat_messages_select_public" on public.chat_messages for select using (is_deleted = false or public.is_admin())';
  end if;
end $$;

-- 3. 举报处理字段
do $$ begin
  if to_regclass('public.chat_message_reports') is not null then
    alter table public.chat_message_reports add column if not exists status text not null default 'pending';
    alter table public.chat_message_reports add column if not exists handled_at timestamptz;
    alter table public.chat_message_reports add column if not exists handled_by uuid references public.profiles(id) on delete set null;

    execute 'drop policy if exists "chat_reports_select_admin" on public.chat_message_reports';
    execute 'create policy "chat_reports_select_admin" on public.chat_message_reports for select using (public.is_admin())';
    execute 'drop policy if exists "chat_reports_update_admin" on public.chat_message_reports';
    execute 'create policy "chat_reports_update_admin" on public.chat_message_reports for update using (public.is_admin()) with check (public.is_admin())';
    grant select, update on public.chat_message_reports to authenticated;
  end if;
end $$;

-- 4. 当前用户安全资料：前端不再直接读取 profiles.role / is_banned 等敏感列
create or replace function public.fw_get_current_profile()
returns table(
  id uuid,
  email text,
  nickname text,
  avatar_url text,
  role text,
  is_banned boolean,
  lab_code text,
  muted_until timestamptz,
  created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select p.id, u.email, p.nickname, p.avatar_url, p.role, p.is_banned, p.lab_code, p.muted_until, p.created_at
  from public.profiles p
  left join auth.users u on u.id = p.id
  where p.id = auth.uid();
$$;

-- 5. 管理员列表 RPC
create or replace function public.admin_list_profiles()
returns table(
  id uuid,
  nickname text,
  avatar_url text,
  role text,
  is_banned boolean,
  lab_code text,
  muted_until timestamptz,
  created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select p.id, p.nickname, p.avatar_url, p.role, p.is_banned, p.lab_code, p.muted_until, p.created_at
  from public.profiles p
  where public.is_admin()
  order by p.created_at desc
  limit 300;
$$;

create or replace function public.admin_list_chat_reports()
returns table(
  id bigint,
  message_id bigint,
  reporter_id uuid,
  reporter_name text,
  target_user_id uuid,
  target_name text,
  room_key text,
  message_content text,
  report_reason text,
  status text,
  created_at timestamptz,
  handled_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select r.id, r.message_id, r.reporter_id, rp.nickname as reporter_name,
         m.user_id as target_user_id, tp.nickname as target_name, m.room_key,
         m.content as message_content, r.report_reason, coalesce(r.status,'pending') as status,
         r.created_at, r.handled_at
  from public.chat_message_reports r
  left join public.chat_messages m on m.id = r.message_id
  left join public.profiles rp on rp.id = r.reporter_id
  left join public.profiles tp on tp.id = m.user_id
  where public.is_admin()
  order by r.created_at desc
  limit 200;
$$;

create or replace function public.admin_list_chat_messages()
returns table(
  id bigint,
  room_key text,
  user_id uuid,
  nickname text,
  avatar_url text,
  content text,
  is_deleted boolean,
  created_at timestamptz
)
language sql
security definer
set search_path = public
as $$
  select m.id, m.room_key, m.user_id, p.nickname, p.avatar_url, m.content, m.is_deleted, m.created_at
  from public.chat_messages m
  left join public.profiles p on p.id = m.user_id
