returns table(
  id bigint,
  captain_id uuid,
  captain_name text,
  game_name text,
  mode text,
  starts_at_text text,
  capacity integer,
  member_count integer,
  note text,
  status text,
  requires_approval boolean,
  created_at timestamptz
)
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admin can read game parties';
  end if;
