drop function if exists public.admin_delete_game_party(bigint,text);
create function public.admin_delete_game_party(p_party_id bigint,p_reason text default '组队房间违规，管理员删除')
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  owner_id uuid;
  party_name text;
begin
  if not public.is_admin() then
    raise exception 'Only admin can delete game parties';
  end if;
  select g.captain_id,g.game_name into owner_id,party_name from public.game_parties g where g.id=p_party_id;
  if not found then
    raise exception 'Game party not found';
  end if;
  delete from public.game_parties where id=p_party_id;
  perform public.fw_log_moderation('game_party',p_party_id::text,owner_id,'delete_game_party',
    coalesce(nullif(btrim(p_reason),''),'组队房间违规，管理员删除') || '（' || coalesce(party_name,'未命名游戏') || '）',null,false,null);
end;
$$;

